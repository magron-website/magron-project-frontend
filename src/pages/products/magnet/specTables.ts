/**
 * 표 id → 표 데이터. id 는 `magnet` i18n 의 families[].tables[].id 와 같아야 한다.
 * (MAGNET_TABLE_IMAGES 와 동일한 키를 쓴다 — 데이터가 없는 표는 이미지로 남는다)
 */
const TABLES: Record<string, SpecTableData> = {
  'sintered-ndfeb': sinteredNdFeB,
  'bonded-compression-ndfeb': bondedCompression,
  'bonded-injection-ndfeb': bondedInjection,
  'magnetic-powder': magneticPowder,
  smco,
  'cast-alnico': castAlNiCo,
  'sintered-alnico': sinteredAlNiCo,
  ferrite,
}

const NOTES_BY_TABLE: Record<string, Record<Language, string[]>> = {
  'sintered-ndfeb': SINTERED_NDFEB_NOTES,
  smco: SMCO_NOTES,
}

/** 표 id 로 사양표 데이터를 가져온다. 없으면 undefined (화면은 이미지로 넘어간다). */
export function getMagnetSpecTable(id: string, lang: Language): SpecTableData | undefined {
  const table = TABLES[id]
  if (!table) return undefined

  const notes = NOTES_BY_TABLE[id]?.[lang]
  return notes ? { ...table, notes } : table
}
